package ir.torob.seller.data.local

import androidx.room.Entity
import androidx.room.PrimaryKey

enum class SyncState {
    SAVED_ON_PHONE,   // Waiting for internet or in retry queue
    UPLOADING,        // Currently in flight
    SYNCED_ON_SERVER, // Successfully acknowledged by server
    FAILED_EXPIRED    // Failed because server rejected or inquiry expired
}

@Entity(tableName = "sync_queue")
data class SyncQueueEntity(
    @PrimaryKey val clientResponseId: String, // Unique UUID generated by device
    val inquiryId: String,
    val offeredPriceToman: Long,
    val isInStock: Boolean,
    val stockCount: Int = 1,
    val notes: String?,
    val status: String? = null,
    val declineReason: String? = null,
    val submittedAt: String,
    val syncState: SyncState = SyncState.SAVED_ON_PHONE,
    val retryCount: Int = 0,
    val lastError: String? = null,
    val createdAt: Long = System.currentTimeMillis()
)
